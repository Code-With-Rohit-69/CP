import java.io.*;
import java.util.Scanner;

/**
 * ANewYearAndDays
 */
public class ANewYearAndDays {

    public static void main(String[] args) {
        Scanner fr = new Scanner(System.in);
        int x = fr.nextInt();
        String type = fr.nextLine().trim();

        if (type.endsWith("week")) {
            System.out.println((x == 5 || x == 6) ? 53 : 52);
        } else {
            System.out.println(x <= 29 ? 12 : (x == 30 ? 11 : 7));
        }
    }
}

