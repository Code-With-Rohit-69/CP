import java.io.*;
import java.util.*;

/**
 * CSerejaAndBrackets
 */
public class CSerejaAndBrackets {

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();
        StringBuilder out = new StringBuilder();

        String s = fr.next();

        int n = s.length();

        ST st = new ST(n);
        st.build(0, s, 0, n - 1);

        int m = fr.nextInt();

        while (m-- > 0) {
            int l = fr.nextInt() - 1;
            int r = fr.nextInt() - 1;

            int[] res = st.query(0, 0, n - 1, l, r);

            out.append(2 * res[2] + "\n");
        }

        System.out.println(out);
    }
}

class ST {
    int[] open, close, full;

    public ST(int n) {
        this.open = new int[4 * n];
        this.close = new int[4 * n];
        this.full = new int[4 * n];
    }

    public void build(int index, String s, int l, int r) {
        if (l == r) {
            if (s.charAt(l) == '(') {
                open[index] = 1;
            } else {
                close[index] = 1;
            }

            return;
        }

        int mid = (l + r) >> 1;

        build(2 * index + 1, s, l, mid);
        build(2 * index + 2, s, mid + 1, r);

        int[] left = new int[]{open[2 * index + 1], close[2 * index + 1], full[2 * index + 1]};
        int[] right = new int[]{open[2 * index + 2], close[2 * index + 2], full[2 * index + 2]};

        int[] curr = merge(left, right);

        open[index] = curr[0];
        close[index] = curr[1];
        full[index] = curr[2];
    }

    public int[] query(int index, int l, int r, int i, int j) {

        if (l > j || r < i)
            return new int[] {0, 0, 0};

        if (l >= i && r <= j) {
            return new int[]{open[index], close[index], full[index]};
        }

        int mid = (l + r) >> 1;

        int[] left = query(2 * index + 1, l, mid, i, j);
        int[] right = query(2 * index + 2, mid + 1, r, i, j);

        return merge(left, right);
    }

    private int[] merge(int[] left, int[] right) {
        int min = Math.min(left[0], right[1]);
        int full = left[2] + right[2] + min;
        int open = left[0] + right[0] - min;
        int close = left[1] + right[1] - min;

        return new int[]{open, close, full};
    }

}

class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

