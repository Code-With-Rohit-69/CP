import java.io.*;
import java.util.*;

/**
 * ALalaLandAndAppleTrees
 */
public class ALalaLandAndAppleTrees {

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();

        int n = fr.nextInt();

        int[][] arr = new int[n][2];
        int nCount = 0, pCount = 0;
        int nSum = 0;
        int pSum = 0;

        for (int i = 0; i < n; i++) {
            arr[i][0] = fr.nextInt();
            arr[i][1] = fr.nextInt();

            if (arr[i][0] < 0) {
                nSum += arr[i][1];
                nCount++;
            } else {
                pSum += arr[i][1];
                pCount++;
            }
        }

        int total = nSum + pSum;

        if (Math.abs(nCount - pCount) < 2) {
            System.out.println(total);
            return;
        }

        Arrays.sort(arr, (a, b) -> a[0] - b[0]);

        // n = 0,  p = 3
        // times = 3 - 0;

        // n = 3, p = 1
        // times = 3 - 1 = 2;

        if (pCount > nCount) {
            int times = pCount - nCount - 1;
            int index = n - 1;

            while (times-- > 0) {
                total -= arr[index][1];
                index--;
            }
        
        } else {
            int times = nCount - pCount - 1;
            int index = 0;

            while (times-- > 0) {
                total -= arr[index][1];
                index++;
            }

        }

        System.out.println(total);

    }
}

class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

