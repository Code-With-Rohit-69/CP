import java.util.*;
import java.io.*;

public class F_Eating_Candies {

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();
        PrintWriter out = new PrintWriter(System.out);

        int t = fr.nextInt();

        while (t-- > 0) {
            int n = fr.nextInt();

            int[] arr = new int[n];
            int[] prefix = new int[n];
            int[] suffix = new int[n];

            for (int i = 0; i < n; i++) {
                arr[i] = fr.nextInt();

                if (i == 0) {
                    prefix[i] = arr[i];
                } else {
                    prefix[i] = prefix[i - 1] + arr[i];
                }
            }

            suffix[n - 1] = arr[n - 1];

            for (int i = n - 2; i >= 0; i--) {
                suffix[i] = suffix[i + 1] + arr[i];
            }

            // print(prefix);
            // print(suffix);

            int ans = 0;

            int i = 0;
            int j = n - 1;

            while (i < j) {
                if(prefix[i] == suffix[j]) {
                    ans = Math.max(ans, i + 1 + n - j);
                    i++;
                    j--;
                } else if(prefix[i] > suffix[j])  {
                    j--;
                } else {
                    i++;
                }
            }

            out.println(ans);
        }

        out.flush();
    }
}

class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

