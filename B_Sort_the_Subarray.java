import java.io.*;

public class B_Sort_the_Subarray {

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();
        PrintWriter out = new PrintWriter(System.out);

        int t = fr.nextInt();

        while (t-- > 0) {
            int n = fr.nextInt();

            int[] A = new int[n];
            int[] B = new int[n];

            for (int i = 0; i < n; i++) {
                A[i] = fr.nextInt();
            }

            for (int i = 0; i < n; i++) {
                B[i] = fr.nextInt();
            }

            int start = -1;
            int end = n;

            int index = 0;

            while (index < n && A[index] == B[index]) {
                index++;
            }

            start = index;

            index = n - 1;

            while (index >= 0 && A[index] == B[index]) {
                index--;
            }

            end = index;

            int min = Integer.MAX_VALUE;
            int max = Integer.MIN_VALUE;

            for (int i = start; i <= end; i++) {
                min = Math.min(min, A[i]);
                max = Math.max(max, A[i]);
            }

            // out.println("start: " + start + " end: " + end + " min: " + min + " max: " + max);

            int i = start, j = end;

            while (i - 1 >= 0 && B[i - 1] <= B[i]) {
                i--;
            }

            while (j + 1 < n && B[j + 1] >= B[j]) {
                j++;
            }

            start = i;
            end = j;

            // out.println("After, start: " + start + " end: " + end);

            out.println((start + 1) + " " + (end + 1));

        }

        out.flush();
    }
}

