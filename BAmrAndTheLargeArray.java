import java.io.*;
import java.util.*;

/**
 * BAmrAndTheLargeArray
 */
public class BAmrAndTheLargeArray {

    final static int INF = (int) (1e9);

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();

        int n = fr.nextInt();
        int[] arr = new int[n];

        HashMap<Integer, Integer> freq = new HashMap<>();
        HashMap<Integer, Integer> firstPos = new HashMap<>();
        HashMap<Integer, Integer> lastPos = new HashMap<>();

        int maxFreq = 0;

        for (int i = 0; i < n; i++) {
            arr[i] = fr.nextInt();

            freq.put(arr[i], freq.getOrDefault(arr[i], 0) + 1);

            if (!firstPos.containsKey(arr[i])) {
                firstPos.put(arr[i], i);
                lastPos.put(arr[i], i);
            } else {
                lastPos.put(arr[i], i);
            }

            if (freq.get(arr[i]) > maxFreq) {
                maxFreq = freq.get(arr[i]);
            }
        }

        int l = -(INF);
        int r = INF;

        for(int key : freq.keySet()) {
            if (freq.get(key) < maxFreq) {
                continue;
            }

            int first = firstPos.get(key);
            int last = lastPos.get(key);

            int len = last - first + 1;

            if (len < r - l + 1) {
                l = first + 1;
                r = last + 1;
            }
        }

        System.out.println(l + " " + r);

    }
}

class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

