import java.io.*;
import java.util.*;


/**
 * ESumOfDigitsAndAgain
 */
public class ESumOfDigitsAndAgain {

    public static int getSum(int num) {
        int sum = 0;

        while(num > 0) {
            sum += num % 10;
            num /= 10;
        }

        return sum;
    }

    public static String generateSuffix(int num) {
        StringBuilder sb = new StringBuilder();

        while (num > 9) {
            int sum = getSum(num);
            sb.append(num);
            num = sum;
        }

        if(num > 0) sb.append(num);

        return sb.toString();
    }

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();
        StringBuilder out = new StringBuilder();

        int t = fr.nextInt();

        while(t-- > 0) {
            String s = fr.next();
            int n = s.length();

            if(n == 1) {
                out.append(s + "\n");
                continue;
            }

            int[] freq = new int[10];

            for(char ch : s.toCharArray()) {
                freq[ch - '0']++;
            }

            for(int i = 1; i <= 9 * n; i++) { //  let last number will be i
                int[] f = freq.clone();

                String suffix = generateSuffix(i);

                boolean ok = true;

                for(char ch : suffix.toCharArray()) {
                    if(f[ch - '0'] <= 0) {
                        ok = false;
                        break;
                    }

                    f[ch - '0']--;
                }

                if(!ok) continue; // not a valid suffix as per given frequency

                int rem = 0;

                for(int j = 0; j < 10; j++) {
                    rem += (j * f[j]);
                }

                
                if(rem == i) {
                    StringBuilder sb = new StringBuilder();
                    int first = -1;

                    for(int j = 1; j < 10; j++) {
                        if(f[j] > 0) {
                            first = j;
                            f[j]--;
                            break;
                        }
                    }

                    if(first != -1) {
                        sb.append(first);

                        while(f[0] > 0) {
                            sb.append(0);
                            f[0]--;
                        }

                        for(int j = 1; j < 10; j++) {
                            while(f[j] > 0) {
                                sb.append(j);
                                f[j]--;
                            }
                        }
                    }

                    sb.append(suffix);

                    out.append(sb.toString() + "\n");
                    break;
                }
            }

        }

        System.out.println(out);

    }
}

class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

