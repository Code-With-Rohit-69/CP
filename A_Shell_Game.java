import java.io.*;
import java.util.*;

/**
 * A_Shell_Game
 */

public class A_Shell_Game {

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader(new FileInputStream("input.txt"));
        PrintWriter out = new PrintWriter(new FileWriter("output.txt"));

        int ball = fr.nextInt();
        int[] arr = new int[4];

        for (int i = 0; i < 4; i++) {
            arr[i] = i;
        }

        for (int i = 0; i < 3; i++) {
            int from = fr.nextInt();
            int to = fr.nextInt();

            int temp = arr[from];
            arr[from] = arr[to];
            arr[to] = temp;

        }

        out.println(arr[ball]);

        out.flush();
        out.close();
    }
}

