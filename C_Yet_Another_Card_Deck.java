import java.util.*;
import java.io.*;

/**
 * C_Yet_Another_Card_Deck
 */
public class C_Yet_Another_Card_Deck {

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();
        PrintWriter out = new PrintWriter(System.out);

        int n = fr.nextInt();
        int q = fr.nextInt();

        int[] indexes = new int[51];

        Arrays.fill(indexes, -1);

        for (int i = 0; i < n; i++) {
            int x = fr.nextInt();

            if(indexes[x] == -1) {
                indexes[x] = i + 1;
            }

        }

        for (int i = 0; i < q; i++) {
            int x = fr.nextInt();

            out.print(indexes[x] + " ");
            
            for (int j = 1; j <= 50; j++) {
                if (indexes[j] != -1 && indexes[j] < indexes[x]) {
                    indexes[j] += 1;
                }
            }

            indexes[x] = 1;
        }

        out.flush();
    }
}

