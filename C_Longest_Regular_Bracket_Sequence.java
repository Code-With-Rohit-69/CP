import java.io.*;
import java.util.*;

public class C_Longest_Regular_Bracket_Sequence {

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();
        PrintWriter out = new PrintWriter(System.out);

        String s = fr.next();
        int n = s.length();

        int max = 0;
        int count = 1;

        Stack<Integer> stack = new Stack<>();
        stack.push(-1);

        for (int i = 0; i < n; i++) {
            char ch = s.charAt(i);

            if (ch == '(') {
                stack.push(i);
            } else {
                stack.pop();

                if (!stack.isEmpty()) {
                    int curr = i - stack.peek();

                    if (curr > max) {
                        max = curr;
                        count = 1;
                    } else if (curr == max) {
                        count++;
                    }
                } else {
                    stack.push(i);
                }
            }
        }

        if (max == 0) {
            out.println(0 + " " + 1);
        } else {
            out.println(max + " " + count);
        }

        out.flush();

    }
}

/*
 * 
 * s = ")((())))(()())"
 * 
 * count = 0;
 * i = 0
 * count = -1;
 * count = 0;
 * i = 1
 * "("
 * i = 2
 * "(("
 * i = 3
 * "((("
 * i = 4
 * count = 2
 * "(("
 * i = 5
 * count = 4
 * "("
 * i = 6
 * count = 6
 * ""
 * max = 6
 * i = 7
 * ""
 * 
 * 
 * 
 */

class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

