import java.io.*;
import java.util.*;

/**
 * DXeniaAndBitOperations
 */
public class DXeniaAndBitOperations {

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();
        
        int N = fr.nextInt(), m = fr.nextInt();

        int n = 1 << N;

        ST st = new ST(n);

        int[] A = new int[n];

        for(int i = 0; i < n; i++) A[i] = fr.nextInt();

        boolean isOr = (N % 2 != 0);

        st.build(A, 0, 0, n - 1, isOr);

        while(m-- > 0) {
            int index = fr.nextInt() - 1;
            int val = fr.nextInt();

            st.update(A, 0, 0, n - 1, isOr, index, val);
            A[index] = val;

            System.out.println(st.query());
        }

    }
}

class ST {
    int[] tree;

    public ST(int n) {
        tree = new int[4 * n];
    }

    public void build(int[] arr, int index, int i, int j, boolean orr) {
        if(i == j) {
            tree[index] = arr[i];
            return;
        }

        int mid = (i + j) >> 1;

        build(arr, 2 * index + 1, i, mid, !orr);
        build(arr, 2 * index + 2, mid + 1, j, !orr);

        if(orr) {
            tree[index] = tree[2 * index + 1] | tree[2 * index + 2];
        } else {
            tree[index] = tree[2 * index + 1] ^ tree[2 * index + 2];
        }
    }

    public void update(int[] arr, int index, int i, int j, boolean orr, int idx, int val) {
        if(i == j) {
            tree[index] = val;
            return;
        }

        int mid = (i + j) >> 1;

        if(idx <= mid) {
            update(arr, 2 * index + 1, i, mid, !orr, idx, val);
        } else {
            update(arr, 2 * index + 2, mid + 1, j, !orr, idx, val);
        }

        if(orr) {
            tree[index] = tree[2 * index + 1] | tree[2 * index + 2];
        } else {
            tree[index] = tree[2 * index + 1] ^ tree[2 * index + 2];
        }

    }

    public int query() {
        return tree[0];
    }

}

class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

