import java.io.*;
import java.util.*;

/**
 * A_Divide_and_Multiply
 */

public class A_Divide_and_Multiply {

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();
        PrintWriter out = new PrintWriter(System.out);

        int tt = fr.nextInt();

        while (tt-- > 0) {
            int n = fr.nextInt();
            long[] arr = new long[n];

            int count = 0;

            for (int i = 0; i < n; i++) {
                arr[i] = fr.nextLong();

                while (arr[i] % 2 == 0) {
                    count++;
                    arr[i] /= 2;
                }
            }

            Arrays.sort(arr);

            long sum = 0L;

            for (int i = 0; i < n - 1; i++) {
                sum += (arr[i] % 2 == 0) ? 1 : arr[i];
            }

            long largest = arr[n - 1];

            while (count > 0) {
                largest = largest * 2;
                count--;
            }

            sum += largest;

            out.println(sum);

        }

        out.flush();
    }
}

/*
 * 
 * n = 3
 * arr = [6, 4, 2]
 * 
 * 3, 1, 1
 * 
 * count = 4
 * 3 * 2 = 6
 * 6 * 2 = 12
 * 12 * 2 = 24
 * 24 * 2 = 48
 * 
 * 
 * 
 */

class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

