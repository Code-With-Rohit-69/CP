import java.io.*;
import java.util.*;

/**
 * D_1_Remove_the_Substring_easy_version
 */
public class D_1_Remove_the_Substring_easy_version {

    static PrintWriter out;

    public static void print(int[] arr) {
        for (int i : arr) {
            out.print(i + " ");
        }

        out.println();
    }

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();
        out = new PrintWriter(System.out);

        String s = fr.next();
        String t = fr.next();

        int n = s.length();
        int m = t.length();

        if (s.equals(t)) {
            out.println(0);
            out.flush();
            return;
        }

        int[] prefix = new int[m];
        int[] suffix = new int[m];

        int index = 0;

        for (int i = 0; i < m; i++) {
            while (index < n && s.charAt(index) != t.charAt(i)) {
                index++;
            }

            prefix[i] = index;
            index++;
        }

        index = n - 1;

        for (int i = m - 1; i >= 0; i--) {
            while (index >= 0 && s.charAt(index) != t.charAt(i)) {
                index--;
            }

            suffix[i] = index;
            index--;
        }

        // print(prefix);
        // print(suffix);

        int max = Math.max(suffix[0], n - 1 - prefix[m - 1]);

        for (int i = 0; i < m - 1; i++) {
            int gap = suffix[i + 1] - prefix[i] - 1;
            max = Math.max(max, gap);
        }

        out.println(max);

        out.flush();

    }
}

class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

