import java.io.*;
import java.util.*;

/**
 * A_Ring_road
 */

public class A_Ring_road {

    static int costA;
    static int total;
    static ArrayList<Edge>[] graph;
    static boolean[] vis;

    public static void dfs(int node, int parent) {

        vis[node] = true;

        for (Edge e : graph[node]) {
            int v = e.v;
            int wt = e.wt;

            if (v == parent) {
                continue;
            }

            if (vis[v]) {
                total += wt;
                if (!e.isOriginal) {
                    costA += wt;
                }
                return;
            }

            if (!e.isOriginal) {
                costA += wt;
            }

            total += wt;
            dfs(v, node);
            return;
        }

    }

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();
        PrintWriter out = new PrintWriter(System.out);

        int n = fr.nextInt();

        graph = new ArrayList[n + 1];
        vis = new boolean[n + 1];

        for (int i = 0; i < n + 1; i++) {
            graph[i] = new ArrayList<>();
        }

        for (int i = 0; i < n; i++) {
            int u = fr.nextInt();
            int v = fr.nextInt();
            int wt = fr.nextInt();

            graph[u].add(new Edge(v, wt, true));
            graph[v].add(new Edge(u, wt, false));
        }

        costA = 0;
        total = 0;

        dfs(1, 0);

        out.println(Math.min(costA, total - costA));

        out.flush();
    }
}

class Edge {
    int v, wt;
    boolean isOriginal;

    public Edge(int v, int wt, boolean isOriginal) {
        this.v = v;
        this.wt = wt;
        this.isOriginal = isOriginal;
    }
}

class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

