import java.io.*;
import java.util.*;

/**
 * B_Network_Topology
 */

public class B_Network_Topology {

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();
        PrintWriter out = new PrintWriter(System.out);

        int N = fr.nextInt();
        int E = fr.nextInt();

        // ArrayList<ArrayList<Integer>> graph = new ArrayList<>();

        // for (int i = 0; i <= n + 1; i++) {
        // graph.add(new ArrayList<>());
        // }

        int[] deg = new int[N + 1];

        for (int i = 0; i < E; i++) {
            int u = fr.nextInt();
            int v = fr.nextInt();

            deg[u]++;
            deg[v]++;
        }

        int count1 = 0;
        int count2 = 0;
        int countCenter = 0;

        for (int i = 1; i <= N; i++) {
            if (deg[i] == 1) {
                count1++;
            } else if (deg[i] == 2) {
                count2++;
            } else if (deg[i] == N - 1) {
                countCenter++;
            }
        }

        if (count2 == N && E == N) {
            out.println("ring topology");
        } else if (count1 == 2 && count2 == N - 2 && E == N - 1) {
            out.println("bus topology");
        } else if (countCenter == 1 && count1 == N - 1 && E == N - 1) {
            out.println("star topology");
        } else {
            out.println("unknown topology");
        }

        out.flush();

        out.flush();

    }
}

class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1)
                return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

