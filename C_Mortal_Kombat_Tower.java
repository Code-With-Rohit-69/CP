    public static int solve(int[] arr) {
        int n = arr.length;

        int[][] dp = new int[n + 1][2];

        dp[n - 1][0] = arr[n - 1];
        dp[n - 1][1] = 0;

        for (int i = n - 2; i >= 0; i--) {
            for (int j = 0; j < 2; j++) {

                if (j == 0) {
                    int costA = arr[i] + dp[i + 1][1];
                    int costB = arr[i] + arr[i + 1] + dp[i + 2][1];

                    dp[i][j] = Math.min(costA, costB);
                } else {
                    int costA = dp[i + 1][0];
                    int costB = dp[i + 2][0];

                    dp[i][j] = Math.min(costA, costB);
                }
            }
        }

        return dp[0][0];
    }

