    public static boolean tabulation(int[] nums, int m) {
        int n = nums.length;

        if (n >= m) return true;

        int[][][] dp = new int[n + 1][m][2]; // len, rem, picked or not

        for (int i = 0; i <= n; i++) {
            dp[i][0][1] = 1;
        }

        for(int i = n - 1; i >= 0; i--) {
            for (int j = 0; j < m; j++) {
                for (int k = 0; k < 2; k++) {
                    if (j == 0 && k == 1) {
                        dp[i][j][k] = 1;
                        continue;
                    }

                    int skip = dp[i + 1][j][k];

                    if (skip == 1) {
                        dp[i][j][k] = 1;
                        continue;
                    }

                    int newRem = ((j + nums[i] % m) + m) % m;
                    int take = dp[i + 1][newRem][1];

                    if (take == 1) {
                        dp[i][j][k] = 1;
                    }

                }
            }
        }

        return dp[0][0][0] == 1;

    }

