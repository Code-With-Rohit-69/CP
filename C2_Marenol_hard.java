import java.io.*;
import java.util.*;

public class C2_Marenol_hard {
    
    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();
        StringBuilder out = new StringBuilder();

        int t = fr.nextInt();

        while (t-- > 0) {
            int n = fr.nextInt();

            String A = fr.next();
            String B = fr.next();

            List<Integer> evenA = new ArrayList<>();
            List<Integer> evenB = new ArrayList<>();
            List<Integer> oddA = new ArrayList<>();
            List<Integer> oddB = new ArrayList<>();

            for (int i = 0; i < n; i++) {
                if (A.charAt(i) == '1') {
                    if ((i & 1) == 0) {
                        evenA.add(i);
                    } else {
                        oddA.add(i);
                    }
                }

                if (B.charAt(i) == '1') {
                    if ((i & 1) == 0) {
                        evenB.add(i);
                    } else {
                        oddB.add(i);
                    }
                }
            }

            if (evenA.size() != evenB.size() || oddA.size() != oddB.size()) {
                out.append("-1 \n");
                continue;
            }

            long count = 0;

            for(int i = 0; i < evenA.size(); i++) {
                count += Math.abs(evenA.get(i) - evenB.get(i)) / 2;
            }

            for(int i = 0; i < oddA.size(); i++) {
                count += Math.abs(oddA.get(i) - oddB.get(i)) / 2;
            }

            out.append(count + "\n");

        }

        System.out.println(out);

    }
}

class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

