
import java.io.*;
import java.util.*;


/**
 * BMinMatrices
 */
public class BMinMatrices {

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();
        StringBuilder out = new StringBuilder();

        int t = fr.nextInt();

        while(t-- > 0) {
            int n = fr.nextInt(), k = fr.nextInt();

            if(k < n || k > 2 * n - 1) {
                out.append("-1\n");
                continue;
            }

            int start = 1;
            int[][] arr = new int[n][n];

            int max = 2 * n - 1;
            int uptoRow = max - k + 1;
            int lastCol = -1;

            for(int i = 0; i < n; i++) {
                if(uptoRow > 0) {
                    arr[i][i] = start++;
                    lastCol = i;
                    uptoRow--;
                } else {
                    arr[i][lastCol] = start++;
                }
            }

            if(start != k) {
                for(int j = lastCol + 1; j < n; j++) {
                    arr[0][j] = start++;
                }
            }

            for(int i = 0; i < n; i++) {
                for(int j = 0; j < n; j++) {
                    if(arr[i][j] == 0) {
                        arr[i][j] = start++;
                    }
                }
            }


            for(int[] A : arr) {
                for(int x : A) {
                    out.append(x + " ");
                }
                out.append("\n");
            }

        }

        System.out.println(out);

    }    
}


class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

