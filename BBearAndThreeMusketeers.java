import java.io.*;
import java.util.*;

/**
 * BBearAndThreeMusketeers
 */
public class BBearAndThreeMusketeers {

    public static void main(String[] args) throws IOException {
        
        FastReader fr = new FastReader();

        int n = fr.nextInt(), m = fr.nextInt();

        ArrayList<ArrayList<Integer>> graph = new ArrayList<>();
        boolean[][] adj = new boolean[n + 1][n + 1];

        for (int i = 0; i < n + 1; i++) {
            graph.add(new ArrayList<>());
        }

        for(int i = 0; i < m; i++) {
            int u = fr.nextInt(), v = fr.nextInt();

            graph.get(u).add(v);
            graph.get(v).add(u);

            adj[u][v] = true;
            adj[v][u] = true;   
        }

        int res = Integer.MAX_VALUE;

        for (int i = 1; i <= n; i++) {
            ArrayList<Integer> list = graph.get(i);
            int size = list.size();

            for (int j = 0; j < size; j++) {
                int u = list.get(j);

                for (int k = j + 1; k < size; k++) {
                    int v = list.get(k);

                    if (adj[u][v]) {
                        
                        int curr = graph.get(i).size() + graph.get(u).size() + graph.get(v).size() - 6;

                        res = Math.min(curr, res);
                    }
                }
            }
        }

        System.out.println(res == Integer.MAX_VALUE ? -1 : res);

    }
}

// 1 => 2 3 4 5 6

class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

