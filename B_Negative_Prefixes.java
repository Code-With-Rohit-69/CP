import java.io.*;
import java.util.*;

/**
 * B_Negative_Prefixes
 */
public class B_Negative_Prefixes {

    public static void main(String[] args) throws IOException {
        FastReader fr = new FastReader();
        PrintWriter out = new PrintWriter(System.out);

        int tt = fr.nextInt();

        while (tt-- > 0) {
            int n = fr.nextInt();
            int[] arr = new int[n];
            ArrayList<Integer> list = new ArrayList<>();

            for (int i = 0; i < n; i++) {
                arr[i] = fr.nextInt();
            }

            int[] valid = new int[n];

            for (int i = 0; i < n; i++) {
                valid[i] = fr.nextInt();
            }

            for (int i = 0; i < n; i++) {
                if (valid[i] == 0) {
                    list.add(arr[i]);
                }
            }

            Collections.sort(list, Comparator.reverseOrder());

            int index = 0;

            for (int i = 0; i < n; i++) {
                if(valid[i] == 0) {
                    arr[i] = list.get(index);
                    index++;
                }
            }

            for (int i = 0; i < n; i++) {
                out.print(arr[i] + " ");
            }

            out.println();

        }


        out.flush();

    }
}

class FastReader {
    private final InputStream in = System.in;
    private final byte[] buffer = new byte[1 << 16];
    private int ptr = 0, len = 0;

    private int read() throws IOException {
        if (ptr >= len) {
            len = in.read(buffer);
            ptr = 0;
            if (len <= 0)
                return -1;
        }
        return buffer[ptr++];
    }

    int nextInt() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        int num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    long nextLong() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        long num = 0;
        while (c > ' ') {
            num = num * 10 + (c - '0');
            c = read();
        }
        return num * sign;
    }

    String next() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return null;
        }
        StringBuilder sb = new StringBuilder();
        while (c > ' ') {
            sb.append((char) c);
            c = read();
        }
        return sb.toString();
    }

    double nextDouble() throws IOException {
        int c;
        while ((c = read()) <= ' ') {
            if (c == -1) return -1;
        }
        int sign = 1;
        if (c == '-') {
            sign = -1;
            c = read();
        }
        double num = 0;
        while (c > ' ' && c != '.') {
            num = num * 10 + (c - '0');
            c = read();
        }
        if (c == '.') {
            double div = 10;
            while ((c = read()) > ' ') {
                num += (c - '0') / div;
                div *= 10;
            }
        }
        return num * sign;
    }
}

